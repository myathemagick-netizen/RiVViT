import assert from 'node:assert/strict';
import {AU_KM,DAY_MS,solveArrival,radialMotion,segmentDistance,minimumDuring,baryPosition,encounterReport} from '../lib/moving-target.mjs';
const position=(body,t)=>body==='Saturn'?{x:0,y:0,z:0}:{x:1,y:0,z:0};
const speed=AU_KM/DAY_MS*1000;
const still=solveArrival({departure:0,speedKmSec:speed,position,maxDays:3});assert.ok(Math.abs(still.travelDays-1)<1e-10);
const moving=(body,t)=>body==='Saturn'?{x:0,y:0,z:0}:{x:1+.2*t/DAY_MS,y:0,z:0};
assert.ok(Math.abs(solveArrival({departure:0,speedKmSec:speed,position:moving,maxDays:3}).travelDays-1.25)<1e-10);
const toward=(body,t)=>body==='Saturn'?{x:0,y:0,z:0}:{x:1-.2*t/DAY_MS,y:0,z:0};
assert.ok(Math.abs(solveArrival({departure:0,speedKmSec:speed,position:toward,maxDays:3}).travelDays-1/1.2)<1e-10);
assert.ok(radialMotion(0,moving).earthRadialKmSec>0);assert.ok(radialMotion(0,toward).earthRadialKmSec<0);
assert.equal(solveArrival({departure:0,speedKmSec:speed/100,position,maxDays:3}),null);
assert.throws(()=>solveArrival({departure:0,speedKmSec:0,position}));
assert.equal(segmentDistance({x:.5,y:1,z:0},{x:0,y:0,z:0},{x:1,y:0,z:0}).distance,1);
assert.equal(segmentDistance({x:2,y:0,z:0},{x:0,y:0,z:0},{x:1,y:0,z:0}).interior,false);
const min=minimumDuring(t=>(t/DAY_MS-.37)**2,0,DAY_MS);assert.ok(Math.abs(min.time/DAY_MS-.37)<1e-7);
const epoch=Date.parse('2017-10-16T00:00:00Z');const actual=solveArrival({departure:epoch,speedKmSec:25});assert.ok(actual.travelDays>500&&actual.travelDays<900);assert.ok(Math.abs(actual.residualAU)<1e-8);
assert.ok(Math.hypot(...Object.values(baryPosition('Sun',epoch)))<.02);
const fake={departure:0,arrival:DAY_MS,source:{x:0,y:0,z:0},target:{x:1,y:0,z:0}};
const crossing=(body,t)=>({x:.8,y:.1*(t/DAY_MS-.1),z:0});
const moon=encounterReport(fake,{position:crossing}).find(row=>row.body==='Moon');
assert.ok(moon.closestSegmentKm<1);assert.ok(moon.closestSameTimeKm>1000000);assert.equal(moon.sphereOverlapCandidate,false);
const coarse=encounterReport(actual,{stepDays:.5}),fine=encounterReport(actual,{stepDays:.125});
assert.ok(coarse.every((r,i)=>r.sphereOverlapCandidate===fine[i].sphereOverlapCandidate));
assert.ok(coarse.every((r,i)=>Math.abs(r.closestSameTimeKm-fine[i].closestSameTimeKm)<100));
console.log('PASS: stationary/moving target, toward/away signs, no arrival, parameter validation, segment geometry, off-grid encounter refinement, and real ephemeris residual.');
